def _lookup_key(model_name):
    key = " ".join((model_name or "").casefold().replace("ё", "е").split())
    key = re.sub(r"\s*,\s*", ",", key)
    return key


def boat_specification_for(model_name):
    """Return a verified record for an exact known model, or ``None``."""
    record_key = ALIASES.get(_lookup_key(model_name))
    return BOAT_SPECIFICATIONS.get(record_key)


def format_parameters(record):
    return "\n".join(f"{name}: {value}" for name, value in record["parameters"])
